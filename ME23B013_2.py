import os
import time
import numpy as np
from PIL import Image
from sklearn.linear_model import LogisticRegression

# =================================================================
# DATA PROCESSING
# =================================================================
def preprocess_and_flatten(image_dir, target_size=(64, 64)):

    X_list = []
    y_list = []
    # Define class mappings
    class_mapping = {'NORMAL': 0, 'PNEUMONIA': 1}

    for class_name, label in class_mapping.items():
        dir_path = os.path.join(image_dir, class_name)
        if not os.path.exists(dir_path):
            continue

        for img_name in sorted(os.listdir(dir_path)):
            if img_name.lower().endswith(('.png', '.jpg', '.jpeg')):
                img_path = os.path.join(dir_path, img_name)

                img=Image.open(img_path).convert('L')

                img_scaled=img.resize(target_size,Image.LANCZOS)
                img_normalized=np.array(img_scaled, dtype=np.float32)/255.0

                img_flattened=img_normalized.reshape(-1)

                X_list.append(img_flattened)
                y_list.append(label)

    X = np.array(X_list)
    y = np.array(y_list)
    return X, y

# =================================================================
# Q1: PRINCIPAL COMPONENT ANALYSIS (PCA)
# =================================================================

def fit_pca(X_train, k):
    """
    Computes mean, covariance eigenvalues, and top k components.
    Uses SVD for numerical stability and speed.
    """
    mu = np.mean(X_train, axis=0)
    X_centered = X_train - mu

    N = X_train.shape[0]
    # SVD: X_centered = U * S * V^T
    _, S, Vt = np.linalg.svd(X_centered, full_matrices=False)

    # Sample covariance eigenvalues: lambda_i = s_i^2 / (N - 1)
    eigenvalues = (S ** 2) / (N - 1)
    W = Vt[:k, :].T

    return eigenvalues[:k], W, mu


def transform_pca(X, W, mu):
    """
    Centers data using training mean and projects onto subspace W.
    """
    return (X - mu) @ W


# =================================================================
# Q2: CHOOSING k BY EXPLAINED VARIANCE
# =================================================================

def find_k_for_variance(eigenvalues, threshold=0.95):
    """
    Calculates minimum components to retain target explained variance.
    """
    eigenvalues = np.maximum(eigenvalues, 0)
    total_variance = np.sum(eigenvalues)

    if total_variance == 0:
        return 1

    explained_ratio = np.cumsum(eigenvalues) / total_variance
    indices = np.where(explained_ratio >= threshold)[0]

    return int(indices[0] + 1) if len(indices) > 0 else len(eigenvalues)


# =================================================================
# Q3: EVALUATION METRICS
# =================================================================

def compute_metrics(y_true, y_pred):
    """
    Computes Precision, Recall, and F1-Score for binary classification.
    """
    y_true = np.asarray(y_true).ravel()
    y_pred = np.asarray(y_pred).ravel()

    TP = np.sum((y_true == 1) & (y_pred == 1))
    FP = np.sum((y_true == 0) & (y_pred == 1))
    FN = np.sum((y_true == 1) & (y_pred == 0))

    precision = TP / (TP + FP) if (TP + FP) > 0 else 0.0
    recall = TP / (TP + FN) if (TP + FN) > 0 else 0.0
    f1_score = (2 * precision * recall / (precision + recall)) if (precision + recall) > 0 else 0.0

    return {
        "precision": precision,
        "recall": recall,
        "f1_score": f1_score
    }


